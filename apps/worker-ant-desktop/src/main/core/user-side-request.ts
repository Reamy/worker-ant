/**
 * zx_20261113_2 M4「通」——识别「下一步必须由用户在本机执行并回报」的收尾话术（零依赖纯模块）。
 *
 * 病根（2026-11-13 真标本 `0396cfbc`）：执行体在正文里写“请在仓库根目录执行…请把最后 15 行贴给我”，
 *   没有调用 `ask_user`。run 随即收口 → 验收门禁判未达 → `paused/acceptance_failed`。
 *   用户看到的是「验收未通过」，而实际语义是「在等你动手」——两者必须分开。
 *
 * 判据故意**窄**：必须同时命中「请/需要你 + 在你本机/终端/仓库根目录 + 执行/运行/跑」与
 *   「贴给我/发给我/告诉我/回报/反馈给我」两类，才认定为用户侧动作请求。
 *   只命中一类（如“如需验证可运行 pnpm test”）不算——那只是建议，不是阻塞式请求。
 */
export function looksLikeUserSideRequest(text: string): boolean {
  const t = (text || '').trim();
  if (!t) return false;
  const imperative = /(请(你|您)?(先)?在[^\n。]{0,60}(执行|运行|跑|操作)|需要你[^\n。]{0,60}(执行|运行|跑)|在你(本机|的终端|终端|电脑)[^\n。]{0,60}(执行|运行|跑))/;
  const reportBack = /(贴给我|发给我|告诉我|回报给我|反馈给我|把(最后|结果|输出|日志)[^\n。]{0,30}(贴|发|给))/;
  return imperative.test(t) && reportBack.test(t);
}
