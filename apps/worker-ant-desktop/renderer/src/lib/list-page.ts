/**
 * zx_20260930 M4-2: 渲染层**列表批次**大小的唯一真源（列表页/区块一批取多少行）。
 *
 * 谁在用：成果页、项目详情页「本项目成果」、任务详情页的对话与成果——三处都是「先取一批、点『加载更多』再取」，
 * 若各自写一个字面量，就会出现"这页 100、那页 200、另一页改了口径忘了改"的第二把尺（本轮的靶心之一）。
 *
 * **刻意不与 main 侧的 `core/pagination.ts` 合并**：那边的 `PAGE_DEFAULT`（同为 100）语义是
 * "调用方**没传** `limit` 时的兜底"，这里语义是"**界面一批取多少**"。今日同值只是为了让"不传参的调用"
 * 与"界面第一页"落在同一批；两边含义不同，合并会让"改界面批次"顺手改动服务端兜底。
 * 三处调用点**都显式传** `limit`，故 main 侧兜底值改了不影响界面（但会夹到 `[1, PAGE_MAX=500]`）。
 */
export const LIST_PAGE_SIZE = 100;

/**
 * 这一批之后还有没有下一页？三处调用点共用此判据（不各写一遍 `rows.length < N`）。
 *
 * 两把尺，各管一段：
 * - **一批没取满**（`loaded < LIST_PAGE_SIZE`）⇒ 服务端已经到底。这是"请求了 `LIST_PAGE_SIZE`
 *   却只回来一行半行"的**短页**信号，与 `total` 无关，故它自己就能判"取尽"。
 * - **取满一批**时，只能看 `total`：它就是服务端全量口径，取到它即取全。
 *
 * ⚠ `total` 必须**已知且为正**才算数。渲染层拿到的是 `Number(d?.total) || 0`——IPC 出错或字段缺失时
 * 会兜成 `0`。若把主判据写成裸的 `loaded >= total`，则那个 `0` 会让 `100 >= 0` 当场成立 ⇒
 * 第一批刚回来就谎报"已取全"，而**用户恰恰因此点不到「加载更多」**，100 行之后的成果再也够不着。
 * 故宁可多给一次（下一批取空即按短页自动收口），也不谎报"取全"。
 */
export function pageExhausted(loaded: number, total: number): boolean {
  if (loaded < LIST_PAGE_SIZE) return true;
  return Number.isFinite(total) && total > 0 && loaded >= total;
}
